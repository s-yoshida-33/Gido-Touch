# Data compression and S3 upload script for Gido-Touch
# Usage: powershell -ExecutionPolicy Bypass -File .\build\compress-data.ps1 -MallId "halong" -DataType "all"
#
# DataType options:
#   shops   - Compress data/{MallId}/files/shops/
#   news    - Compress data/{MallId}/files/news/
#   events  - Compress data/{MallId}/files/events/
#   json    - Compress data/{MallId}/json/
#   all     - json + auto-scan all subdirectories under data/{MallId}/files/
#
# S3 upload paths:
#   s3://tti-distribution/public/gido-touch/data/{MallId}/files/{subtype}/
#   s3://tti-distribution/public/gido-touch/data/{MallId}/json/
#
# Local source layout:
#   data/{MallId}/files/shops/    <- shop logo images ({shopId}/thumbW640_logo.webp ...)
#   data/{MallId}/files/news/     <- news images
#   data/{MallId}/files/events/   <- event images
#   data/{MallId}/json/           <- shoplist.json etc.
#
# Release output (local staging area, gitignored):
#   release/{MallId}/data/files/{subtype}/{subtype}-{timestamp}.zip + latest.json
#   release/{MallId}/data/json/json-{timestamp}.zip + latest.json
#
# Note on meta files:
#   S3 meta  : latest.json          (generated by this script, uploaded to S3)
#   Local meta: .{subtype}-meta.json (generated by Tauri download side after extraction)

param(
    [string]$MallId = "",
    [string]$DataType = ""
)

chcp 65001 | Out-Null
$OutputEncoding = [System.Text.Encoding]::UTF8
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
[Console]::InputEncoding  = [System.Text.Encoding]::UTF8

$ErrorActionPreference = "Stop"

# Require MallId
if ([string]::IsNullOrWhiteSpace($MallId)) {
    Write-Host "Mall ID (e.g. halong): " -NoNewline
    $MallId = Read-Host
    if ([string]::IsNullOrWhiteSpace($MallId)) {
        Write-Host "Error: Mall ID is required." -ForegroundColor Red
        exit 1
    }
}

# Require DataType
$validDataTypes = @("shops", "news", "events", "json", "all")
if ([string]::IsNullOrWhiteSpace($DataType) -or $validDataTypes -notcontains $DataType) {
    Write-Host "Data type [shops / news / events / json / all]: " -NoNewline
    $DataType = Read-Host
    if ([string]::IsNullOrWhiteSpace($DataType) -or $validDataTypes -notcontains $DataType) {
        Write-Host "Error: DataType must be one of: $($validDataTypes -join ', ')." -ForegroundColor Red
        exit 1
    }
}

Write-Host "Processing data for mall: $MallId (type: $DataType)" -ForegroundColor Cyan

$rootDir  = Split-Path -Parent $PSScriptRoot
$dataRoot = Join-Path $rootDir "data"
$today    = Get-Date -Format "yyyy-MM-dd-HH-mm-ss"

# ---------------------------------------------------------------------------
# Helper: Compress a source dir into a ZIP and generate latest.json, then upload
# ---------------------------------------------------------------------------
function Compress-And-Upload {
    param(
        [string]$SourceDir,
        [string]$OutputDir,
        [string]$ZipPrefix,
        [string]$S3Base
    )

    # Validate source
    if (-not (Test-Path $SourceDir)) {
        Write-Host "  Error: Source directory not found: $SourceDir" -ForegroundColor Red
        return $false
    }

    # Get non-hidden files recursively
    $files = Get-ChildItem -Path $SourceDir -File -Recurse | Where-Object { $_.Name -notmatch '^\.' }

    if ($files.Count -eq 0) {
        Write-Host "  No files found in $SourceDir (skipped)" -ForegroundColor Yellow
        return $false
    }

    Write-Host "  Found $($files.Count) file(s):" -ForegroundColor Green
    $files | ForEach-Object {
        $rel = $_.FullName.Substring($SourceDir.Length).TrimStart('\', '/')
        Write-Host "    - $rel" -ForegroundColor Gray
    }

    # Prepare output dir
    if (-not (Test-Path $OutputDir)) {
        New-Item -ItemType Directory -Path $OutputDir -Force | Out-Null
        Write-Host "  Created output directory: $OutputDir" -ForegroundColor Green
    }

    $zipFileName = "$ZipPrefix-$today.zip"
    $zipPath     = Join-Path $OutputDir $zipFileName
    $latestPath  = Join-Path $OutputDir "latest.json"

    # Remove existing zip if present
    if (Test-Path $zipPath) {
        Remove-Item $zipPath -Force
    }

    # Compress
    try {
        Write-Host "  Compressing to ZIP file..." -ForegroundColor Cyan
        Compress-Archive -Path "$SourceDir\*" -DestinationPath $zipPath -Force

        $fileSize   = (Get-Item $zipPath).Length
        $fileSizeMB = [Math]::Round($fileSize / 1MB, 2)
        Write-Host "  Compressed: $zipPath ($fileSizeMB MB)" -ForegroundColor Green
    } catch {
        Write-Host "  Error during compression: $_" -ForegroundColor Red
        return $false
    }

    # Generate latest.json
    $updatedAt  = (Get-Date).ToUniversalTime().ToString("yyyy-MM-ddTHH:mm:ssZ")
    $latestJson = @{ zip = $zipFileName; updated_at = $updatedAt } | ConvertTo-Json -Compress
    [System.IO.File]::WriteAllText($latestPath, $latestJson, [System.Text.Encoding]::UTF8)
    Write-Host "  Generated latest.json: zip=$zipFileName, updated_at=$updatedAt" -ForegroundColor Green

    $displayUrl = ($S3Base -replace 's3://tti-distribution/public/', 'https://dl.tti.ninja/public/') + "/"
    Write-Host "  -> $displayUrl" -ForegroundColor Gray

    # Upload if AWS CLI available
    if (Get-Command aws -ErrorAction SilentlyContinue) {
        # Archive existing S3 ZIPs before uploading
        $archiveDir = Join-Path $OutputDir "archive"
        if (-not (Test-Path $archiveDir)) {
            New-Item -ItemType Directory -Path $archiveDir -Force | Out-Null
        }

        aws s3 sync "$S3Base/" $archiveDir --exclude "latest.json" 2>&1 | Out-Null

        $archivedFiles = Get-ChildItem -Path $archiveDir -File -ErrorAction SilentlyContinue
        if ($archivedFiles.Count -gt 0) {
            Write-Host "  Archived $($archivedFiles.Count) existing ZIP(s) to: $archiveDir" -ForegroundColor Green
            $archivedFiles | ForEach-Object { Write-Host "    - $($_.Name)" -ForegroundColor Gray }

            Write-Host "  Cleaning up old ZIPs from S3..." -ForegroundColor Cyan
            aws s3 rm "$S3Base/" --recursive --exclude "latest.json"
            Write-Host "  S3 cleanup complete." -ForegroundColor Green
        } else {
            Write-Host "  No existing ZIPs on S3 (first upload)." -ForegroundColor Gray
            Remove-Item $archiveDir -Force -Recurse -ErrorAction SilentlyContinue
        }

        try {
            aws s3 cp $zipPath "$S3Base/$zipFileName" --content-type "application/zip"
            Write-Host "  Uploaded: $zipFileName" -ForegroundColor Green

            aws s3 cp $latestPath "$S3Base/latest.json" `
                --content-type "application/json" `
                --cache-control "no-cache, no-store"
            Write-Host "  Uploaded: latest.json (Cache-Control: no-cache)" -ForegroundColor Green
        } catch {
            Write-Host "  Upload failed: $_" -ForegroundColor Red
            Write-Host "  Please upload manually:" -ForegroundColor Yellow
            Write-Host "    aws s3 cp `"$zipPath`" `"$S3Base/$zipFileName`" --content-type application/zip" -ForegroundColor Gray
            Write-Host "    aws s3 cp `"$latestPath`" `"$S3Base/latest.json`" --content-type application/json --cache-control no-cache,no-store" -ForegroundColor Gray
        }
    } else {
        Write-Host "  [INFO] AWS CLI not found. Upload manually:" -ForegroundColor Yellow
        Write-Host "    aws s3 cp `"$zipPath`" `"$S3Base/$zipFileName`" --content-type application/zip" -ForegroundColor Gray
        Write-Host "    aws s3 cp `"$latestPath`" `"$S3Base/latest.json`" --content-type application/json --cache-control no-cache,no-store" -ForegroundColor Gray
    }

    return $true
}

# ---------------------------------------------------------------------------
# Process a files/ subtype (shops, news, events, ...)
# ---------------------------------------------------------------------------
function Process-FilesSubtype {
    param([string]$Subtype)

    Write-Host "`n[$($Subtype.ToUpper())]" -ForegroundColor Magenta

    $sourceDir = Join-Path $dataRoot "$MallId\files\$Subtype"
    $outputDir = Join-Path $rootDir "release\$MallId\data\files\$Subtype"
    $s3Base    = "s3://tti-distribution/public/gido-touch/data/$MallId/files/$Subtype"

    Compress-And-Upload -SourceDir $sourceDir -OutputDir $outputDir -ZipPrefix $Subtype -S3Base $s3Base
}

# ---------------------------------------------------------------------------
# Process json/
# ---------------------------------------------------------------------------
function Process-Json {
    Write-Host "`n[JSON]" -ForegroundColor Magenta

    $sourceDir = Join-Path $dataRoot "$MallId\json"
    $outputDir = Join-Path $rootDir "release\$MallId\data\json"
    $s3Base    = "s3://tti-distribution/public/gido-touch/data/$MallId/json"

    Compress-And-Upload -SourceDir $sourceDir -OutputDir $outputDir -ZipPrefix "json" -S3Base $s3Base
}

# ---------------------------------------------------------------------------
# Run selected data type(s)
# ---------------------------------------------------------------------------
switch ($DataType) {
    "shops"  { Process-FilesSubtype -Subtype "shops" }
    "news"   { Process-FilesSubtype -Subtype "news" }
    "events" { Process-FilesSubtype -Subtype "events" }
    "json"   { Process-Json }
    "all" {
        # Auto-scan files/ subdirectories
        $filesBaseDir = Join-Path $dataRoot "$MallId\files"
        if (Test-Path $filesBaseDir) {
            $subtypeDirs = Get-ChildItem -Path $filesBaseDir -Directory -ErrorAction SilentlyContinue
            if ($subtypeDirs.Count -gt 0) {
                foreach ($subtypeDir in $subtypeDirs) {
                    Process-FilesSubtype -Subtype $subtypeDir.Name
                }
            } else {
                Write-Host "`n[FILES] No subdirectories found under: $filesBaseDir" -ForegroundColor Yellow
            }
        } else {
            Write-Host "`n[FILES] Directory not found: $filesBaseDir" -ForegroundColor Yellow
        }

        # Process json/
        Process-Json
    }
}

Write-Host "`nDone!" -ForegroundColor Green
